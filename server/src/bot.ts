import { Bot, webhookCallback } from 'grammy'
import { BOT_TOKEN } from './auth'
import { APP_URL } from './env'

export const bot = BOT_TOKEN ? new Bot(BOT_TOKEN) : null

const OPEN = 'Играть ⚔️'

export function appKeyboard(startParam?: string) {
  if (!APP_URL) return undefined
  const url = startParam ? `${APP_URL}?startapp=${encodeURIComponent(startParam)}` : APP_URL
  return { inline_keyboard: [[{ text: OPEN, web_app: { url } }]] }
}

if (bot) {
  void bot.api.setMyDescription(
    'Легион это уютная стратегия про захват мира. Командуй армиями, занимай ' +
      'соседние земли в бою на кубиках и собирай под своим знаменем целые регионы.\n\n' +
      'Ход простой: получи подкрепления, расставь их на границах, атакуй соседей и ' +
      'в конце перебрось войска туда, где жарче всего. Кто останется единственным ' +
      'правителем карты, тот и победил.\n\n' +
      'Можно играть с ботами в одиночку на трёх уровнях сложности или позвать друзей ' +
      'в общую комнату по коду из четырёх букв.\n\n' +
      'Заходи на карту, когда захочется покомандовать.',
  ).catch(() => {})
  void bot.api.setMyShortDescription('Уютная стратегия про захват мира. Играй с ботами или зови друзей ⚔️').catch(() => {})

  // Стандартное меню команд (список по «/»).
  void bot.api.setMyCommands([
    { command: 'start', description: 'Открыть игру' },
    { command: 'play', description: 'Сыграть партию' },
    { command: 'rules', description: 'Как играть' },
    { command: 'about', description: 'Об игре' },
    { command: 'help', description: 'Помощь' },
  ]).catch(() => {})

  bot.command('start', async ctx => {
    const payload = ctx.match?.toString() ?? ''
    // ссылка-приглашение вида /start room_ABCD открывает сразу нужную комнату
    const startParam = payload.startsWith('room_') ? payload : undefined
    const name = ctx.from?.first_name || 'полководец'
    await ctx.reply(
      `Привет, ${name}! Это Легион ⚔️\n\n` +
        'Если совсем просто, это уютная стратегия про захват мира. На карте двадцать ' +
        'земель, поделённых на пять регионов. Ты командуешь своими армиями и шаг за ' +
        'шагом занимаешь территории соседей.\n\n' +
        'Ход из трёх частей: сначала получаешь подкрепления и расставляешь их по своим ' +
        'землям, потом атакуешь соседние в бою на кубиках, а в конце можешь перебросить ' +
        'войска на угрожаемые границы.\n\n' +
        'Займёшь весь регион целиком, будешь получать за него бонус. Победит тот, кто ' +
        'останется единственным правителем карты.\n\n' +
        'Ничего сложного: можно сыграть с ботами в одиночку, а можно позвать друзей в ' +
        'общую комнату по коду. Жми кнопку «Играть» внизу и принимай командование. Удачи на карте! ⚔️',
      { reply_markup: appKeyboard(startParam) },
    )
  })

  bot.command('play', async ctx => {
    await ctx.reply('Разворачиваю армии ⚔️ Принимай командование!', { reply_markup: appKeyboard() })
  })

  bot.command('rules', async ctx => {
    await ctx.reply(
      'Правила Легиона ⚔️\n\n' +
        'Цель: остаться единственным правителем карты.\n\n' +
        'Ход состоит из трёх фаз:\n' +
        '1. Подкрепление. Получаешь новые армии (чем больше земель, тем больше) и ' +
        'ставишь их на свои территории. За полный регион идёт бонус.\n' +
        '2. Наступление. Атакуешь соседние вражеские земли. Бой на кубиках: у ' +
        'нападающего до трёх кубиков, у защитника до двух, ничья в пользу защиты.\n' +
        '3. Манёвр. Перебрасываешь армии между своими соседними землями и заканчиваешь ход.\n\n' +
        'Захватишь последнюю землю соперника, он выбывает. Заняв всю карту, ты побеждаешь.\n\n' +
        'Совет: держи границы крепкими, а прорывайся там, где у врага тонко.',
      { reply_markup: appKeyboard() },
    )
  })

  bot.command('about', async ctx => {
    await ctx.reply(
      'Легион ⚔️\n\n' +
        'Тёплая настольная стратегия про захват мира в духе классических варгеймов, ' +
        'только своя: свой мир из двадцати земель, свои регионы и свои правила.\n\n' +
        'Как можно играть:\n' +
        '• Одиночная игра против ботов, три уровня сложности.\n' +
        '• Быстрая игра, случайные соперники онлайн.\n' +
        '• С друзьями, общая комната по коду из четырёх символов.\n\n' +
        'Спокойно, вдумчиво, на пару партий за вечер. Заходи покомандовать ⚔️',
      { reply_markup: appKeyboard() },
    )
  })

  bot.command('help', async ctx => {
    await ctx.reply(
      'Легион ⚔️ - стратегия про захват мира.\n\n' +
        'Команды:\n' +
        '/start - открыть игру\n' +
        '/play - сыграть партию\n' +
        '/rules - как играть\n' +
        '/about - об игре\n' +
        '/help - это сообщение\n\n' +
        'Жми кнопку ниже, чтобы играть 👇',
      { reply_markup: appKeyboard() },
    )
  })
}

export const botWebhook = bot ? webhookCallback(bot, 'hono') : null
